"""Convert the agreed markdown drafts in the owners' folders into LaTeX section snippets for the report.

Run from project/:  python report/md2tex.py
Rewrites report/sections/from_martin_results.tex, from_martin_methods.tex, from_martin_m6.tex and
from_martin_caption1.tex from Martin/results_part1.md and Martin/methods_networks.md. Rerun whenever Martin
updates those files; do not edit the generated files by hand (edit the markdown, or move the text into the
section file and stop regenerating it).
"""
import re
from pathlib import Path

OUT = Path("report/sections")


def tex(md):
    s = md.strip()
    s = re.sub(r"\s*\[[^\]]*\]", "", s)                    # Martin's source notes in square brackets
    s = s.replace("\\", "\\textbackslash{}")
    for a, b in (("&", "\\&"), ("%", "\\%"), ("#", "\\#"), ("_", "\\_"), ("~", "\\textasciitilde{}")):
        s = s.replace(a, b)
    s = re.sub(r"`([^`]+)`", r"\\texttt{\1}", s)
    s = re.sub(r"\*\*(.+?)\*\*", r"\\textbf{\1}", s, flags=re.S)
    s = re.sub(r"(?<![\w*])\*(.+?)\*(?![\w*])", r"\\emph{\1}", s, flags=re.S)
    s = re.sub(r'["\u201c]([^"\u201d]+)["\u201d]', r"``\1''", s)
    s = re.sub(r"Fig\. 1([A-D])(?:, ([A-D]))?",
               lambda m: "Fig.~1\\emph{" + m.group(1) + "}" + (" and \\emph{" + m.group(2) + "}" if m.group(2) else ""), s)
    s = s.replace("Fig. 1", "Fig.~1")
    s = re.sub(r"\{cite:([\w,]+)\}", r"\\cite{\1}", s)       # {cite:key} in the markdown -> \cite{key}
    paras = [" ".join(l.strip() for l in p.splitlines()) for p in re.split(r"\n\s*\n", s)]
    return "\n\n".join(p for p in paras if p)


def between(text, start, end=None):
    i = text.index(start) + len(start)
    j = text.index(end, i) if end else len(text)
    return text[i:j]


r = Path("Martin/results_part1.md").read_text(encoding="utf-8")
blocks = r.split("\n---\n")
head = "% Generated by report/md2tex.py from Martin/results_part1.md. Do not edit by hand.\n"
(OUT / "from_martin_results.tex").write_text(head + tex(blocks[1]) + "\n", encoding="utf-8")
cap = blocks[2].strip().replace("**Figure 1.**", "").strip()
(OUT / "from_martin_caption1.tex").write_text(head + "\\caption{" + tex(cap) + "}\n", encoding="utf-8")
m6 = between(r, "## For part 3 (Anas): the M6 paragraph, ready to paste or shorten", "\n---\n")
(OUT / "from_martin_m6.tex").write_text(head + tex(m6) + "\n", encoding="utf-8")
m = Path("Martin/methods_networks.md").read_text(encoding="utf-8").split("\n---\n")[1]
# S2 result (Diego, 22 Nov), filled in here until Martin updates his markdown:
S2 = ("Whether each turn is attributed to the right speaker was checked by hand on 60 turns drawn at random: all 60 "
      "were assigned to the member the Record names as speaker (95% Wilson interval 94% to 100%).")
m = re.sub(r"\(Whether each turn is attributed to the right speaker was checked on a sample of 60\s+turns: S2, result to fill in\.\)", S2, m)
(OUT / "from_martin_methods.tex").write_text(
    "% Generated by report/md2tex.py from Martin/methods_networks.md. Do not edit by hand.\n" + tex(m) + "\n", encoding="utf-8")
print("wrote", sorted(p.name for p in OUT.glob("from_martin_*.tex")))
